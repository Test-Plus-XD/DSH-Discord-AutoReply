/**
 * Build dist/ with `node build.ts`: strip the types from every source module
 * (Node's own stripper, so no toolchain) and point relative imports at the .js
 * outputs. dist/ is committed because installs from GitHub land in node_modules,
 * where Node refuses to strip types at load time.
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { stripTypeScriptTypes } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const out = join(root, 'dist')
// types.ts is type-only (all its imports are `import type`), and build.ts is this script.
const skip = new Set(['build.ts', 'types.ts'])
const sources = readdirSync(root).filter(file => file.endsWith('.ts') && !skip.has(file))

rmSync(out, { recursive: true, force: true })
mkdirSync(out)
for (const file of sources) {
  const js = stripTypeScriptTypes(readFileSync(join(root, file), 'utf8'))
    .replace(/(from\s+['"]\.\/[\w-]+)\.ts(['"])/g, '$1.js$2')
  writeFileSync(join(out, file.replace(/\.ts$/, '.js')), `// Generated by build.ts from ${file}; edit the .ts source.\n${js}`)
  console.log(`dist/${file.replace(/\.ts$/, '.js')}`)
}
